        private static void WriteHeaders(IXLWorksheet ws, string[] headers)
        {
            for (var i = 0; i < headers.Length; i++)
            {
                ws.Cell(1, i + 1).Value = headers[i];
            }

            ws.Range(1, 1, 1, headers.Length).Style.Font.Bold = true;
            ws.Range(1, 1, 1, headers.Length).Style.Fill.BackgroundColor = XLColor.LightGray;
            ws.SheetView.FreezeRows(1);
        }

        private static (DateTime FromDate, DateTime ToDate) ResolveDateRange(
            ExecutiveStatsExtractFilterVm filter)
        {
            var today = DateTime.Today;

            if (string.Equals(filter.PeriodType, "Weekly", StringComparison.OrdinalIgnoreCase))
            {
                var diff = ((int)today.DayOfWeek + 6) % 7;
                var monday = today.AddDays(-diff);
                var sunday = monday.AddDays(6);

                return (monday, sunday);
            }

            if (string.Equals(filter.PeriodType, "Monthly", StringComparison.OrdinalIgnoreCase))
            {
                var firstDay = new DateTime(today.Year, today.Month, 1);
                var lastDay = firstDay.AddMonths(1).AddDays(-1);

                return (firstDay, lastDay);
            }

            if (filter.FromDate == null || filter.ToDate == null)
                throw new InvalidOperationException("From date and To date are required for a custom extract.");

            if (filter.FromDate.Value.Date > filter.ToDate.Value.Date)
                throw new InvalidOperationException("From date cannot be later than To date.");

            return (filter.FromDate.Value.Date, filter.ToDate.Value.Date);
        }

        private static int CountStatus(List<ExecutiveStatsRow> rows, string status)
        {
            return rows.Count(x => IsStatus(x.Status, status));
        }

        private static bool IsStatus(string? value, string status)
        {
            return Clean(value) == Clean(status);
        }

        private static string Clean(string? value)
        {
            return string.IsNullOrWhiteSpace(value)
                ? string.Empty
                : value.Trim().ToUpperInvariant();
        }

