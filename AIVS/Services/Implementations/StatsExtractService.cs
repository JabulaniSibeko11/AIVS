            }

            ws.Columns().AdjustToContents();
        }

        private static void BuildValuerSheet(
            XLWorkbook workbook,
            List<ExecutiveStatsRow> rows)
        {
            var ws = workbook.Worksheets.Add("Valuer Stats");

            var headers = new[]
            {
                "Valuer",
                "Valuer UserId",
                "Sector",
                "Total Assigned",
                "Claimed",
                "Under Review",
                "Inspection Required",
                "Inspection Confirmed",
                "Inspection Details Sent",
                "Inspection Expired",
                "Returned",
                "Ready OVVIO",
                "Rejected"
            };

            WriteHeaders(ws, headers);

            var data = rows
                .Where(x =>
                    !string.IsNullOrWhiteSpace(x.AssignedToUserId) ||
                    !string.IsNullOrWhiteSpace(x.ValuerUserId))
                .GroupBy(x => new
                {
                    UserId = !string.IsNullOrWhiteSpace(x.ValuerUserId)
                        ? x.ValuerUserId
                        : x.AssignedToUserId,

                    Name = !string.IsNullOrWhiteSpace(x.Valuer)
                        ? x.Valuer
                        : x.AssignedTo,

                    Sector = x.Sector
                })
                .Select(g => new
                {
                    Valuer = string.IsNullOrWhiteSpace(g.Key.Name) ? "Unknown Valuer" : g.Key.Name!,
                    UserId = g.Key.UserId,
                    Sector = g.Key.Sector,
                    Total = g.Count(),
                    Claimed = g.Count(x => IsStatus(x.Status, "Claimed")),
                    UnderReview = g.Count(x => IsStatus(x.Status, "ValuerReview")),
                    InspectionRequired = g.Count(x => IsStatus(x.Status, "InspectionRequired")),
                    InspectionConfirmed = g.Count(x => IsStatus(x.Status, "InspectionConfirmed")),
                    InspectionDetailsSent = g.Count(x => IsStatus(x.Status, "InspectionDetailsSent")),
                    InspectionExpired = g.Count(x => IsStatus(x.Status, "InspectionExpired")),
                    Returned = g.Count(x => IsStatus(x.Status, "ReturnedToClient")),
                    ReadyOvvio = g.Count(x => IsStatus(x.Status, "ReadyForOvvioExtract")),
                    Rejected = g.Count(x => IsStatus(x.Status, "Rejected"))
                })
                .OrderBy(x => x.Valuer)
                .ToList();

            var rowNo = 2;

            foreach (var item in data)
            {
                ws.Cell(rowNo, 1).Value = item.Valuer;
                ws.Cell(rowNo, 2).Value = item.UserId;
                ws.Cell(rowNo, 3).Value = item.Sector;
                ws.Cell(rowNo, 4).Value = item.Total;
                ws.Cell(rowNo, 5).Value = item.Claimed;
                ws.Cell(rowNo, 6).Value = item.UnderReview;
                ws.Cell(rowNo, 7).Value = item.InspectionRequired;
                ws.Cell(rowNo, 8).Value = item.InspectionConfirmed;
                ws.Cell(rowNo, 9).Value = item.InspectionDetailsSent;
                ws.Cell(rowNo, 10).Value = item.InspectionExpired;
                ws.Cell(rowNo, 11).Value = item.Returned;
                ws.Cell(rowNo, 12).Value = item.ReadyOvvio;
                ws.Cell(rowNo, 13).Value = item.Rejected;
                rowNo++;
            }

            ws.Columns().AdjustToContents();
        }

