        private readonly AttributesDbContext _context;
        private readonly IAivsRoleAccessService _roleAccess;

        public StatsExtractService(AttributesDbContext context, IAivsRoleAccessService roleAccess)
        {
            _context = context;
            _roleAccess = roleAccess;
        }

        public async Task<byte[]> BuildExecutiveStatsExtractAsync(
            AivsCurrentUserVm currentUser,
            ExecutiveStatsExtractFilterVm filter)
        {
            if (!_roleAccess.HasPermission(currentUser, AivsPermission.ExportStatistics))
                throw new InvalidOperationException("You do not have permission to export executive stats.");

            var dateRange = ResolveDateRange(filter);

            var fromDate = dateRange.FromDate.Date;
            var toDateExclusive = dateRange.ToDate.Date.AddDays(1);

            var rows = await _context.AttrPropertyInfo
                .AsNoTracking()
                .Where(x =>
                    x.IsActive == true &&
                    (
                        (x.UpdatedDate != null && x.UpdatedDate >= fromDate && x.UpdatedDate < toDateExclusive) ||
                        (x.UpdatedDate == null && x.SubmissionDateTime >= fromDate && x.SubmissionDateTime < toDateExclusive)
                    ))
                .Select(x => new ExecutiveStatsRow
                {
                    AttrId = x.Attr_ID,
                    AttrNo = x.Attr_No,
                    PropertyDescription = x.Property_Desc,
                    PropertyType = x.Property_Type,
                    PremiseId = x.Premise_id,
                    Sector = x.RoutedSector ?? x.Sector,
                    Status = x.Attr_Status,

                    SubmittedByName = x.SubmittedByName,
                    SubmittedByEmail = x.SubmittedByEmail,
                    SubmissionDateTime = x.SubmissionDateTime,

                    AssignedTo = x.Task_Assigned_To,
                    AssignedToUserId = x.Task_Assigned_To_UserId,
                    AssignedDateTime = x.Task_Assigned_DateTime,

                    Valuer = x.Valuer,
                    ValuerUserId = x.ValuerUserId,
                    ValuerDecision = x.ValuerDecision,
                    ValuerDecisionDateTime = x.ValuerDecisionDateTime,

                    PhysicalInspectionRequired = x.Physical_Inspection_Required,
                    PhysicalInspectionStatus = x.Physical_Inspection_Status,
                    InspectionScheduledDate = x.Inspection_Scheduled_Date,
                    InspectionScheduledTime = x.Inspection_Scheduled_Time,
                    InspectionOutcome = x.Inspection_Outcome,

                    ReadyForOvvioExtract = x.ReadyForOvvioExtract,
                    OvvioExtractStatus = x.OvvioExtractStatus,
                    OvvioExtractBatchNo = x.OvvioExtractBatchNo,
                    OvvioExtractDateTime = x.OvvioExtractDateTime,

                    EvidenceCount = x.Evidence_Count,
                    IsWithdrawn = x.IsWithdrawn,

                    CreatedDate = x.CreatedDate,
                    UpdatedDate = x.UpdatedDate
                })
                .OrderBy(x => x.Sector)
                .ThenBy(x => x.Valuer)
                .ThenBy(x => x.AttrNo)
                .ToListAsync();

            using var workbook = new XLWorkbook();

            BuildSummarySheet(workbook, rows, filter.PeriodType, fromDate, dateRange.ToDate, currentUser);
            BuildStatusSheet(workbook, rows);
            BuildSectorSheet(workbook, rows);
            BuildValuerSheet(workbook, rows);
            BuildDetailSheet(workbook, rows);

            using var stream = new MemoryStream();
            workbook.SaveAs(stream);

            return stream.ToArray();
        }

        private static void BuildSummarySheet(
            XLWorkbook workbook,
            List<ExecutiveStatsRow> rows,
            string periodType,
            DateTime fromDate,
            DateTime toDate,
            AivsCurrentUserVm currentUser)
        {
            var ws = workbook.Worksheets.Add("Summary");

            ws.Cell(1, 1).Value = "AIVS Executive Stats Extract";
            ws.Cell(1, 1).Style.Font.Bold = true;
            ws.Cell(1, 1).Style.Font.FontSize = 16;

            ws.Cell(3, 1).Value = "Period Type";
            ws.Cell(3, 2).Value = periodType;

            ws.Cell(4, 1).Value = "From Date";
            ws.Cell(4, 2).Value = fromDate.ToString("yyyy-MM-dd");

            ws.Cell(5, 1).Value = "To Date";
            ws.Cell(5, 2).Value = toDate.ToString("yyyy-MM-dd");

            ws.Cell(6, 1).Value = "Generated By";
            ws.Cell(6, 2).Value = currentUser.FullName;

            ws.Cell(7, 1).Value = "Generated Date";
            ws.Cell(7, 2).Value = DateTime.Now.ToString("yyyy-MM-dd HH:mm");

            var startRow = 10;

            ws.Cell(startRow, 1).Value = "Metric";
            ws.Cell(startRow, 2).Value = "Total";

            ws.Range(startRow, 1, startRow, 2).Style.Font.Bold = true;
            ws.Range(startRow, 1, startRow, 2).Style.Fill.BackgroundColor = XLColor.LightGray;

            var metrics = new List<(string Label, int Count)>
            {
                ("Total Records", rows.Count),
                ("Sector Inbox", CountStatus(rows, "SectorInbox")),
                ("Claimed", CountStatus(rows, "Claimed")),
                ("Under Review", CountStatus(rows, "ValuerReview")),
                ("Inspection Required", CountStatus(rows, "InspectionRequired")),
                ("Inspection Confirmed", CountStatus(rows, "InspectionConfirmed")),
                ("Inspection Details Sent", CountStatus(rows, "InspectionDetailsSent")),
                ("Inspection Expired", CountStatus(rows, "InspectionExpired")),
                ("Returned To Client", CountStatus(rows, "ReturnedToClient")),
                ("Ready For OVVIO Extract", CountStatus(rows, "ReadyForOvvioExtract")),
                ("Senior Manager QA", CountStatus(rows, "SeniorManagerQa")),
                ("Rejected", CountStatus(rows, "Rejected")),
                ("Withdrawn", rows.Count(x => x.IsWithdrawn == true))
            };

            var rowNo = startRow + 1;

            foreach (var metric in metrics)
            {
                ws.Cell(rowNo, 1).Value = metric.Label;
                ws.Cell(rowNo, 2).Value = metric.Count;
                rowNo++;
            }

            ws.Columns().AdjustToContents();
        }

        private static void BuildStatusSheet(
            XLWorkbook workbook,
            List<ExecutiveStatsRow> rows)
        {
            var ws = workbook.Worksheets.Add("Status Breakdown");

            ws.Cell(1, 1).Value = "Status";
            ws.Cell(1, 2).Value = "Total";

            ws.Range(1, 1, 1, 2).Style.Font.Bold = true;
            ws.Range(1, 1, 1, 2).Style.Fill.BackgroundColor = XLColor.LightGray;

            var data = rows
                .GroupBy(x => string.IsNullOrWhiteSpace(x.Status) ? "Unknown" : x.Status.Trim())
                .Select(g => new
                {
                    Status = g.Key,
                    Total = g.Count()
                })
                .OrderByDescending(x => x.Total)
                .ToList();

            var rowNo = 2;

            foreach (var item in data)
            {
                ws.Cell(rowNo, 1).Value = item.Status;
                ws.Cell(rowNo, 2).Value = item.Total;
                rowNo++;
            }

            ws.Columns().AdjustToContents();
        }

        private static void BuildSectorSheet(
            XLWorkbook workbook,
