        {
            var ws = workbook.Worksheets.Add("Sector Stats");

            var headers = new[]
            {
                "Sector",
                "Total",
                "Sector Inbox",
                "Claimed",
                "Under Review",
                "Inspection Required",
                "Inspection Confirmed",
                "Inspection Details Sent",
                "Inspection Expired",
                "Returned",
                "Ready OVVIO",
                "Rejected"
            };

            WriteHeaders(ws, headers);

            var data = rows
                .GroupBy(x => string.IsNullOrWhiteSpace(x.Sector) ? "Unknown" : x.Sector.Trim())
                .Select(g => new
                {
                    Sector = g.Key,
                    Total = g.Count(),
                    SectorInbox = g.Count(x => IsStatus(x.Status, "SectorInbox")),
                    Claimed = g.Count(x => IsStatus(x.Status, "Claimed")),
                    UnderReview = g.Count(x => IsStatus(x.Status, "ValuerReview")),
                    InspectionRequired = g.Count(x => IsStatus(x.Status, "InspectionRequired")),
                    InspectionConfirmed = g.Count(x => IsStatus(x.Status, "InspectionConfirmed")),
                    InspectionDetailsSent = g.Count(x => IsStatus(x.Status, "InspectionDetailsSent")),
                    InspectionExpired = g.Count(x => IsStatus(x.Status, "InspectionExpired")),
                    Returned = g.Count(x => IsStatus(x.Status, "ReturnedToClient")),
                    ReadyOvvio = g.Count(x => IsStatus(x.Status, "ReadyForOvvioExtract")),
                    Rejected = g.Count(x => IsStatus(x.Status, "Rejected"))
                })
                .OrderBy(x => x.Sector)
                .ToList();

            var rowNo = 2;

            foreach (var item in data)
